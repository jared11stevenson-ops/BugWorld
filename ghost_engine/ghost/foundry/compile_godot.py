"""World Compiler for discovered concepts: spec(s) + evidence -> godot/generated/ (data, scenes, golden traces, assets, manifest).
The Godot runtime (godot/ghost/concept.gd + concept_arena.gd) is generic; a 'compiled game' is data + a scene + proof."""
import json, os, random
from ..kernel import rng as R
from . import dsl, agents as A, grammar as G, seeds as S

ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
GEN = os.path.join(ROOT, "godot", "generated")
PAIRS = [(8, 0), (8, 6), (8, 7), (8, 8), (9, 10), (11, 7), (6, 1), (7, 8)]


def gd(obj):
    txt = json.dumps(obj, sort_keys=True)
    assert "true" not in txt and "false" not in txt and "null" not in txt
    return txt


def golden_for(spec, seeds=(11, 12, 13)):
    rows = []
    n = len(spec["actions"])
    for p0, p1 in PAIRS:
        for sd in seeds:
            q0 = p0 if p0 < 6 else p0
            m = A.play(spec, q0, p1, sd * 1009 + p0 * 17 + p1)
            rows.append([p0, p1, sd * 1009 + p0 * 17 + p1, "%08x" % dsl.match_digest(spec, m), m["winner"], m["round"]])
    return rows


def assets_for(spec):
    vars_ = [v[0] for v in spec["vars"]]
    return {"meters": [f"meter_{v}" for v in vars_], "action_icons": [f"icon_{a['name']}" for a in spec["actions"]],
            "sfx": [f"sfx_{a['name']}" for a in spec["actions"]] + ["sfx_win", "sfx_lose"],
            "note": "Derived from the concept's variables and actions. Godot build uses built-in controls until assets exist."}


def concept_scene(idx, cid):
    return ('[gd_scene load_steps=2 format=3]\n\n[ext_resource type="Script" path="res://ghost/concept_arena.gd" id="1"]\n\n'
            f'[node name="ConceptGame_{cid}" type="Control"]\nlayout_mode = 3\nanchors_preset = 15\nanchor_right = 1.0\nanchor_bottom = 1.0\n'
            f'script = ExtResource("1")\nmetadata/concept_index = {idx}\n')


def parity_exotic():
    """Exercises every DSL operator incl. rnd, truncating division of negatives, min/max, !, &&, ||, saturation."""
    V = lambda w, n: ["v", w, n]
    return {"id": "px_exotic", "name": "Parity Exotic",
            "vars": [["a", 5, -20, 40], ["b", 3, -20, 40], ["c", 0, -20, 40]],
            "actions": [
                {"name": "x0", "cond": 0, "fx": [["+=", "me", "a", ["/", ["-", V("opp", "b"), 9], 2]], ["+=", "opp", "c", ["rnd", 4]]]},
                {"name": "x1", "cond": ["&&", [">=", V("me", "a"), 1], ["!", [">", V("me", "c"), 30]]],
                 "fx": [["+=", "me", "b", ["-", ["min", ["+", V("me", "b"), 3], ["max", V("opp", "a"), 2]], V("me", "b")]], ["+=", "opp", "a", ["-", 0, ["rnd", 6]]]]},
                {"name": "x2", "cond": ["||", ["==", ["round"], 2], ["<", V("me", "b"), 4]],
                 "fx": [["+=", "me", "c", ["?", ["!=", ["act", "opp"], 2], ["/", -7, 2], ["*", 2, ["rnd", 3]]]], ["+=", "opp", "b", -1]]}],
            "passive": [["+=", "me", "a", 1], ["+=", "opp", "c", ["rnd", 2]]],
            "end": [[[">=", V("me", "a"), 30], 1], [["<=", V("me", "a"), -15], -1]], "tiebreak": "a", "max_rounds": 18,
            "value": [["a", 2], ["b", 1], ["c", -1]]}


def compile_concepts(entries, n_fuzz=12):
    """entries: list of {"spec", "meta": {...evidence...}}"""
    os.makedirs(GEN, exist_ok=True)
    cdir = os.path.join(GEN, "concepts")
    os.makedirs(cdir, exist_ok=True)
    for f in os.listdir(cdir):
        os.remove(os.path.join(cdir, f))
    concepts, golden = [], {}
    for i, e in enumerate(entries):
        sp = e["spec"]
        errs = dsl.validate(sp)
        if errs:
            raise ValueError(f"{sp.get('id')} invalid: {errs}")
        concepts.append({"spec": sp, "evidence": e.get("evidence", {}), "text": dsl.spec_text(sp)})
        golden[sp["id"]] = golden_for(sp)
        with open(os.path.join(cdir, f"concept_{sp['id']}.tscn"), "w") as f:
            f.write(concept_scene(i, sp["id"]))
        with open(os.path.join(cdir, f"assets_{sp['id']}.json"), "w") as f:
            json.dump(assets_for(sp), f, indent=1)
    rnd = random.Random(777)
    fuzz = {}
    ex = parity_exotic()
    assert not dsl.validate(ex), dsl.validate(ex)
    fuzz[ex["id"]] = {"spec": ex, "golden": golden_for(ex, (21, 22, 23, 24, 25))}
    for k in range(n_fuzz):
        sp, _ = G.random_spec(rnd, f"fz{k}")
        fuzz[sp["id"]] = {"spec": sp, "golden": golden_for(sp, (21, 22))}
    with open(os.path.join(GEN, "concepts.gd"), "w") as f:
        f.write("# GENERATED by ghost.foundry.compile_godot - do not edit.\nextends RefCounted\n\n")
        f.write("const CONCEPTS := " + gd([{"spec": c["spec"], "evidence": c["evidence"], "text": c["text"]} for c in concepts]) + "\n")
    with open(os.path.join(GEN, "concept_golden.gd"), "w") as f:
        f.write("# GENERATED from the Python interpreter - do not edit.\nextends RefCounted\n\n")
        f.write("const GOLDEN := " + gd(golden) + "\nconst FUZZ := " + gd(fuzz) + "\n")
    with open(os.path.join(GEN, "concepts_export.json"), "w") as f:
        json.dump([{"spec": c["spec"], "evidence": c["evidence"]} for c in concepts], f, indent=1)
    manifest = {"concepts": [c["spec"]["id"] for c in concepts], "fuzz_specs": len(fuzz),
                "golden_matches": sum(len(v) for v in golden.values()) + sum(len(v["golden"]) for v in fuzz.values())}
    with open(os.path.join(GEN, "concepts_manifest.json"), "w") as f:
        json.dump(manifest, f, indent=1)
    return manifest


if __name__ == "__main__":
    ents = [{"spec": s, "evidence": {"source": "seed"}} for s in S.all_seeds()]
    print(compile_concepts(ents))
