"""Runs the full experiment suite and writes evidence/ + a REPORT.md whose numbers are generated from the data.
Usage: python -m ghost.lab.experiments [--quick]"""
import json, os, subprocess, sys, time
from ..kernel import rules as RU
from . import evolve as E, causal as CA

ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
OUT = os.path.join(ROOT, "evidence", "lab")


def dump(name, obj):
    os.makedirs(OUT, exist_ok=True)
    with open(os.path.join(OUT, name), "w") as f:
        json.dump(obj, f, indent=1, sort_keys=True)


def git_rev():
    try:
        return subprocess.check_output(["git", "rev-parse", "--short", "HEAD"], cwd=ROOT, text=True).strip()
    except Exception:
        return "unknown"


def full_rules(name, combat):
    r = RU.clone(RU.BASELINE)
    r["name"] = name
    r["combat"] = dict(combat)
    RU.validate(r)
    return r


def main(quick=False):
    t0 = time.time()
    P = dict(gens=6, pop=10, fights=8, seeds=3, ab_seeds=8, ab_ticks=300, cf_seeds=8, fuzz=40, evo_runs=1) if quick else \
        dict(gens=20, pop=20, fights=16, seeds=3, ab_seeds=30, ab_ticks=600, cf_seeds=30, fuzz=150, evo_runs=3)
    meta = {"git_rev": git_rev(), "params": P, "train_seeds": E.TRAIN_SEEDS, "holdout_seeds": E.HOLDOUT_SEEDS,
            "command": "python -m ghost.lab.experiments" + (" --quick" if quick else "")}

    # 1. evolution (several independent runs; champion picked by TRAIN fitness only)
    runs = []
    log = open(os.path.join(OUT, "evolution_log.jsonl"), "w") if os.makedirs(OUT, exist_ok=True) is None else None
    for rs in range(1, P["evo_runs"] + 1):
        best, hist, hall = E.evolve(seed=rs, generations=P["gens"], pop=P["pop"], fights=P["fights"],
                                    log=lambda r, rs=rs: (log.write(json.dumps(dict(r, run=rs)) + "\n"), log.flush()))
        runs.append({"seed": rs, "best": best, "history": hist, "hall": hall, "train_fitness": hist[-1]["best"]})
        print(f"[{time.time()-t0:5.0f}s] evolution run {rs}: train fitness {hist[0]['best']:.3f} -> {hist[-1]['best']:.3f}")
    log.close()
    champion_run = max(runs, key=lambda r: r["train_fitness"])
    champion = champion_run["best"]
    dump("evolution_runs.json", [{"seed": r["seed"], "best": r["best"], "train_curve": [(h["gen"], h["best"], h["mean"]) for h in r["history"]], "hall": r["hall"]} for r in runs])

    # 2. held-out validation
    cands = {"baseline_v0": RU.BASELINE["combat"]}
    for p in E.proposals():
        cands[p["name"]] = p["combat"]
    for r in runs:
        cands[f"evolved_run{r['seed']}"] = r["best"]
    val = E.validate(cands, fights=max(P["fights"], 16))
    dump("holdout_validation.json", val)
    print(f"[{time.time()-t0:5.0f}s] holdout validation done")

    # 3. ablation + sensitivity
    abl = E.ablate(champion, fights=16)
    sens = CA.sensitivity(champion, fights=16)
    dump("ablation.json", abl)
    dump("sensitivity.json", sens)

    # 4. world A/B and counterfactuals
    champ_rules = full_rules("v1_evolved", champion)
    base_rules = full_rules("v0_baseline", RU.BASELINE["combat"])
    ab = CA.ab_test(base_rules, champ_rules, range(1, P["ab_seeds"] + 1), P["ab_ticks"])
    dump("world_ab.json", ab)
    cfs = [CA.counterfactual(champ_rules, range(1, P["cf_seeds"] + 1), 100, 300, k) for k in ("kill_deadliest", "kill_richest", "windfall", "force_war")]
    dump("counterfactuals.json", cfs)
    print(f"[{time.time()-t0:5.0f}s] world A/B + counterfactuals done")

    # 5. exploit fuzz
    fz = CA.fuzz(P["fuzz"], seed=1, ticks=400)
    dump("fuzz_summary.json", {k: v for k, v in fz.items() if k != "rows"})
    dump("fuzz_rows.json", fz["rows"])
    print(f"[{time.time()-t0:5.0f}s] fuzz done")

    os.makedirs(os.path.join(ROOT, "rulesets"), exist_ok=True)
    for r in (base_rules, champ_rules):
        with open(os.path.join(ROOT, "rulesets", r["name"] + ".json"), "w") as f:
            json.dump(r, f, indent=1, sort_keys=True)
    meta["elapsed_s"] = time.time() - t0
    dump("meta.json", meta)
    write_report(meta, runs, val, abl, sens, ab, cfs, fz, champion, quick)
    print(f"done in {time.time()-t0:.0f}s -> {OUT}")


def pct(x):
    return f"{100*x:.0f}%"


def write_report(meta, runs, val, abl, sens, ab, cfs, fz, champion, quick):
    L = []
    w = L.append
    w("# Lab report (generated by `ghost.lab.experiments`; do not edit by hand)\n")
    w(f"git `{meta['git_rev']}` · command `{meta['command']}` · {meta['elapsed_s']:.0f}s · train seeds {list(meta['train_seeds'])} · holdout seeds {list(meta['holdout_seeds'])}\n")
    if quick:
        w("> QUICK MODE: tiny budgets, numbers are for smoke-testing only.\n")
    w("## 1. Mechanic evolution (combat)\n")
    for r in runs:
        h = r["history"]
        w(f"- run seed {r['seed']}: train fitness {h[0]['best']:.3f} (gen 0) → {h[-1]['best']:.3f} (gen {h[-1]['gen']}), {h[-1]['evaluations']} genome evaluations")
    w("\n**Held-out validation** (disjoint seeds; mean ± std of fitness over 8 seeds, paired gain vs baseline)\n")
    w("| candidate | fitness | paired gain | seeds improved | robust dominance↓ | top static score | distinct best responses↑ | RPS cycles↑ | live actions↑ (of 4) | stalemate↓ | fight length | adaptive skill |")
    w("|---|---|---|---|---|---|---|---|---|---|---|---|")
    for k, v in val.items():
        m = v["metrics"]
        gain = f"{v['paired_gain_mean']:+.3f} ± {v['paired_gain_std']:.3f}" if "paired_gain_mean" in v else "—"
        imp = f"{v['seeds_improved']}/8" if "seeds_improved" in v else "—"
        w(f"| {k} | {v['mean']:.3f} ± {v['std']:.3f} | {gain} | {imp} | {m['dominance']:.2f} | {m['top_score']:.2f} | {m['distinct_best_responses']:.1f} | {m['cycles']:.1f} | {m['live_actions']:.1f} | {pct(m['stalemate'])} | {m['length']:.1f} | {m['skill']:.2f} |")
    w("\nChampion (selected by TRAIN fitness only) combat parameters that differ from baseline:\n")
    diff = {k: (RU.BASELINE['combat'][k], v) for k, v in champion.items() if v != RU.BASELINE['combat'][k]}
    w("`" + json.dumps({k: f"{a}→{b}" for k, (a, b) in diff.items()}) + "`\n")
    w("**Ablation** (revert one mechanic module to baseline; drop in held-out fitness = measured contribution):\n")
    w("| module | evolved | contribution |")
    w("|---|---|---|")
    for mod, r in sorted(abl["modules"].items(), key=lambda kv: -kv[1]["contribution"]):
        w(f"| {mod} | {r['evolved']} | {r['contribution']:+.3f} |")
    w("\n**Sensitivity** (±2 steps on one parameter; max |Δ fitness|):\n")
    w(", ".join(f"{r['param']} {r['max_abs_fitness_change']:.3f}" for r in sens["rows"]) + "\n")
    w("## 2. World-level A/B (v0 vs evolved combat inside the persistent world)\n")
    w(f"Paired by seed, {meta['params']['ab_seeds']} worlds × {meta['params']['ab_ticks']} ticks. Difference = evolved − baseline, ±95% CI.\n")
    w("| metric | v0 | evolved | diff ± CI |")
    w("|---|---|---|---|")
    for k in ("alive", "kills", "fights", "wars", "trades", "gini", "richest_share", "conservation_error"):
        v = ab[k]
        w(f"| {k} | {v['a']:.2f} | {v['b']:.2f} | {v['diff']['mean']:+.2f} ± {v['diff']['ci95']:.2f} |")
    w("\n## 3. Counterfactual branches (fork at tick 100, compare next 300 ticks, paired by seed)\n")
    w("| intervention | timelines diverged | kills Δ | wars Δ | alive Δ | trades Δ | gini Δ |")
    w("|---|---|---|---|---|---|---|")
    for c in cfs:
        e = c["effects"]
        f = lambda k: f"{e[k]['paired_diff']['mean']:+.2f} ± {e[k]['paired_diff']['ci95']:.2f}"
        w(f"| {c['kind']} | {pct(c['diverged_fraction'])} | {f('kills')} | {f('wars')} | {f('alive')} | {f('trades')} | {f('gini')} |")
    w("\nA Δ whose ± interval spans 0 is *not* a detected effect, even though the timelines diverged.\n")
    w(f"## 4. Exploit fuzzing ({fz['n']} random rulesets, {fz['ticks']} ticks each)\n")
    w("| flag | rulesets flagged | strongest parameter associations (standardized mean difference) |")
    w("|---|---|---|")
    for k, n in fz["summary"].items():
        d = fz["drivers"].get(k, [])
        w(f"| {k} | {n}/{fz['n']} | " + "; ".join(f"{x['param']} ({x['flagged_mean']} vs {x['unflagged_mean']}, d={x['std_diff']})" for x in d) + " |")
    w("\nAssociations are correlational over random samples, not causal proofs.\n")
    with open(os.path.join(ROOT, "evidence", "REPORT.md"), "w") as f:
        f.write("\n".join(L) + "\n")


if __name__ == "__main__":
    main("--quick" in sys.argv)
